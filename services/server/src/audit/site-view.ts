/** Allowed keys an action still hides (a shared key name that carries thread-derived text there). */
export const SITE_HIDDEN_BY_ACTION: Readonly<Record<string, readonly string[]>> = {
  // A thread folder's name is the member's own label for their conversations.
  "thread_folder.created": ["name"],
  "thread_folder.deleted": ["name"],
};

interface AuditEventLike {
  readonly action: string;
  readonly teamId: string | null;
  readonly target: Record<string, unknown>;
}

/** The target as the Site audit view shows it (as stored for Site-level events). */
export function siteViewTarget(e: AuditEventLike): Record<string, unknown> {
  if (e.teamId === null) return e.target;
  const extra = SITE_HIDDEN_BY_ACTION[e.action] ?? [];
  return Object.fromEntries(
    Object.entries(e.target).filter(([k]) => SITE_VIEW_TARGET_KEYS.has(k) && !extra.includes(k)),
  );
}

/** The event with its target as the Site audit view shows it. */
export function siteViewEvent<E extends AuditEventLike>(e: E): E {
  return e.teamId === null ? e : { ...e, target: siteViewTarget(e) };
}
